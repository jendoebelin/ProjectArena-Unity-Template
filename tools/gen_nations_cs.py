"""Writes Assets/ProjectArena/Avatar/Nations.cs from the native app/src/nations.inc (generated there by
tools/gen_flags.py; APPEND-ONLY: the position + 1 is the country number sent with the avatar).
Usage: python -I tools/gen_nations_cs.py NATIVE_REPO"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(sys.argv[1], 'app', 'src', 'nations.inc'), encoding='utf-8').read()
row = re.compile(r'\{"([^"]*)", "([^"]*)", "([^"]*)", \{\{(\d+), (\d+), (\d+)\}, \{(\d+), (\d+), (\d+)\}, \{(\d+), (\d+), (\d+)\}\}, '
                 r'\{\{([-\d.]+)f, ([-\d.]+)f, ([-\d.]+)f\}, \{([-\d.]+)f, ([-\d.]+)f, ([-\d.]+)f\}\}\}')
rows = row.findall(src)
lines = ['// Generated by tools/gen_nations_cs.py from the native app/src/nations.inc -- do not edit. NATIONS (country',
         '// presets): APPEND-ONLY, the position + 1 is the country number in AvatarDesc. kit = jersey primary, secondary,',
         '// accent (sRGB); team = glow colours (linear, brightest channel 1) by preference.',
         'namespace ProjectArena',
         '{',
         '    public static partial class Avatar',
         '    {',
         '        static readonly Nation[] kNations =',
         '        {']
for r in rows:
    k = ', '.join(r[3:12])
    t = ', '.join(x + 'f' for x in r[12:18])
    lines.append('            new Nation("%s", "%s", "%s", new byte[] { %s }, new float[] { %s }),' % (r[0], r[1], r[2], k, t))
lines += ['        };', '    }', '}', '']
open(os.path.join(ROOT, 'Assets', 'ProjectArena', 'Avatar', 'Nations.cs'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('%d nations' % len(rows))
